const { chromium } = require(process.env.TEMP + '/eon-responsive-qa/node_modules/playwright-core');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
 const page=await browser.newPage({viewport:{width:390,height:844}});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:5173/');
 await page.locator('.side-navigation__toggle').click();
 assert.equal(await page.locator('.side-navigation__link:visible').count(),6);
 await page.keyboard.press('Tab'); await page.keyboard.press('Escape');
 assert.equal(await page.locator('.side-navigation__toggle').getAttribute('aria-expanded'),'false');
 assert.equal(await page.locator('.side-navigation__toggle').evaluate(e=>e===document.activeElement),true);
 await page.locator('.side-navigation__toggle').click();
 await page.locator('a[href="#join"]').click();
 await page.waitForFunction(()=>getComputedStyle(document.querySelector('.join__form')).opacity==='1');
 assert.equal(await page.locator('.join__form').evaluate(e=>getComputedStyle(e).opacity),'1');
 await page.locator('#name').fill('Responsive QA'); await page.locator('#email').fill('qa@example.com');
 await page.route('https://formspree.io/**',r=>r.fulfill({status:500,body:'{}'}));
 await page.locator('.join__button').click();
 await page.locator('[role="alert"]').waitFor();
 await page.screenshot({path:'docs/responsive/after/390-form-error.png'});
 await page.unroute('https://formspree.io/**');
 await page.route('https://formspree.io/**',r=>r.fulfill({status:200,contentType:'application/json',body:'{}'}));
 await page.locator('.join__button').click(); await page.locator('.success').waitFor();
 await page.screenshot({path:'docs/responsive/after/390-form-success.png'});
 await page.close();
 for(const width of [320,768,1920]){
  const p=await browser.newPage({viewport:{width,height:width===1920?1080:844}});
  await p.goto('http://127.0.0.1:5173/');
  await p.locator('#resonance').scrollIntoViewIfNeeded();
  await p.waitForTimeout(1800); await p.screenshot({path:`docs/responsive/after/${width}-resonance-question.png`});
  await p.waitForTimeout(17000); await p.screenshot({path:`docs/responsive/after/${width}-resonance-logo.png`});
  await p.close();
 }
 const reduced=await browser.newPage({viewport:{width:320,height:568},reducedMotion:'reduce'});
 await reduced.goto('http://127.0.0.1:5173/');
 assert.equal(await reduced.locator('.join__form').evaluate(e=>getComputedStyle(e).visibility),'visible');
 assert.equal(await reduced.locator('.availability__statement--hidden').first().evaluate(e=>getComputedStyle(e).opacity),'1');
 await reduced.screenshot({path:'docs/responsive/after/320-reduced-motion.png',fullPage:true});
 await reduced.close();
 const zoom=await browser.newPage({viewport:{width:640,height:360},reducedMotion:'reduce'});
 await zoom.goto('http://127.0.0.1:5173/');
 const zoomOverflow=await zoom.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 await zoom.screenshot({path:'docs/responsive/after/200-percent-reflow.png',fullPage:true});
 assert.equal(zoomOverflow,false);
 assert.deepEqual(errors,[]);
 fs.writeFileSync('docs/responsive/after/interactions.json',JSON.stringify({menuKeyboard:true,menuAnchors:true,formError:true,formSuccess:true,externalSubmission:'mocked; no real data sent',reducedMotion:true,reflow200:'640x360 CSS pixels, equivalent layout space to 1280x720 at 200%; not native browser zoom',pageErrors:errors},null,2));
 await browser.close(); console.log('Interactions passed');
})().catch(e=>{console.error(e);process.exit(1)});
